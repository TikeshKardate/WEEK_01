// This is the main class named AgeOfHarry
public class AgeOfHarry { 

   // Main method is the entry point of the program
    public static void main (String[] args) { 
	
	    // Declares and initializes the current year as 2024
        int currentYear = 2024; 
		
		// Declares and initializes the birth year as 2000
        int birthYear = 2000; 
		
			// Calculates the age by subtracting birth year from current year
        int age = currentYear - birthYear;
		
		// Prints the calculated age to the console
        System.out.println("Harry's age in 2024 is " + age); 
    }
}
